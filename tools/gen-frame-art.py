"""Generate include/FrameArt.h from the three frame tiles in dist/textures/interface/apocrypharealm.

Scaleform's img:// protocol does not resolve loose DDS files (1.3.3 test, 2026-10-18: every spelling shows the
engine's "img" placeholder), so the frame is drawn from the real art's pixels with the clip drawing API instead.
The corner tile is run-length encoded per row; the two edge tiles are one-pixel-thick strips (a nine-slice edge
is the same along its run), so one column / one row of each is kept.

Usage: python tools/gen-frame-art.py   (run from the repo root; needs Pillow)
"""
import os
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tiles = os.path.join(root, 'dist', 'textures', 'interface', 'apocrypharealm')


def load(name):
    return Image.open(os.path.join(tiles, name)).convert('RGBA')


corner = load('lmuframe_corner.dds')
edge_h = load('lmuframe_edge_h.dds')
edge_v = load('lmuframe_edge_v.dds')
w, h = corner.size
assert (w, h) == (26, 26)

out = []
out.append('// GENERATED by tools/gen-frame-art.py from dist/textures/interface/apocrypharealm/*.dds - do not edit.')
out.append('#pragma once')
out.append('#include <cstdint>')
out.append('')
out.append('namespace frameart')
out.append('{')
out.append('\tstruct Run { std::uint8_t x, y, len; std::uint32_t rgb; std::uint8_t alpha; };')
out.append('\tstruct Px { std::uint32_t rgb; std::uint8_t alpha; };')
out.append('\tconstexpr int kTile = 26;')
out.append('')
runs = []
px = corner.load()
for y in range(h):
    x = 0
    while x < w:
        r, g, b, a = px[x, y]
        if a == 0:
            x += 1
            continue
        n = 1
        while x + n < w and px[x + n, y] == (r, g, b, a):
            n += 1
        runs.append((x, y, n, (r << 16) | (g << 8) | b, round(a * 100 / 255)))
        x += n
out.append('\tconstexpr Run kCorner[] = {')
for x, y, n, rgb, a in runs:
    out.append('\t\t{ %d, %d, %d, 0x%06X, %d },' % (x, y, n, rgb, a))
out.append('\t};')
out.append('')


def strip(name, pixels):
    out.append('\tconstexpr Px %s[kTile] = {' % name)
    for r, g, b, a in pixels:
        out.append('\t\t{ 0x%06X, %d },' % ((r << 16) | (g << 8) | b, round(a * 100 / 255)))
    out.append('\t};')
    out.append('')


eh = edge_h.load()
ev = edge_v.load()
strip('kEdgeHRows', [eh[w // 2, y] for y in range(h)])      # row y of the horizontal strip
strip('kEdgeVCols', [ev[x, h // 2] for x in range(w)])      # column x of the vertical strip
out.append('}')
with open(os.path.join(root, 'include', 'FrameArt.h'), 'w', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print('runs', len(runs))
